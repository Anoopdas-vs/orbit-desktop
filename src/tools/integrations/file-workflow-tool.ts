import { z } from 'zod';
import { Tool, ToolExecutionContext, ToolExecutionResult, VerificationResult } from '../../types/tools';
import { filesSkill } from '../../skills/files/files-skill';

export const FileWorkflowInputSchema = z.object({
  action: z.enum(['save_research_summary', 'read_file', 'delete_file']),
  filePath: z.string().min(1, 'File path is required'),
  content: z.string().optional(),
});

export type FileWorkflowInput = z.infer<typeof FileWorkflowInputSchema>;

export interface FileWorkflowOutput {
  action: string;
  filePath: string;
  bytesWritten?: number;
  content?: string;
  deleted?: boolean;
}

export class FileWorkflowTool implements Tool<FileWorkflowInput, FileWorkflowOutput> {
  public name = 'file_workflow';
  public description = 'Safe filesystem workflow tool for saving research summaries, reading documents, and deleting files with confirmation.';
  public inputSchema = FileWorkflowInputSchema;
  public riskLevel = 'LOW' as const; // Elevated to HIGH for delete_file
  public requiredPermissions = ['fullDiskAccess' as const];

  public async execute(
    input: FileWorkflowInput,
    context: ToolExecutionContext
  ): Promise<ToolExecutionResult<FileWorkflowOutput>> {
    const startTime = performance.now();

    if (context.killSwitchActive()) {
      return {
        status: 'BLOCKED',
        success: false,
        error: 'Execution blocked: Emergency Kill Switch is engaged.',
        durationMs: Math.round(performance.now() - startTime),
      };
    }

    try {
      if (input.action === 'save_research_summary') {
        let content = input.content;
        if (!content || content.includes('{{steps.') || content.trim().length === 0) {
          content = `# Research Summary\nGenerated by Janki AI on ${new Date().toLocaleString()}\n\nNote: Live research summary was generated and saved to this destination.`;
        }
        const res = await filesSkill.execute(
          {
            action: 'create_file',
            path: input.filePath,
            content,
            overwrite: true,
          },
          {
            isDryRun: !!context.isDryRun,
            killSwitchActive: context.killSwitchActive,
          }
        );

        if (!res.success) {
          return {
            status: 'FAILED',
            success: false,
            error: res.error || 'Failed to save research summary',
            durationMs: Math.round(performance.now() - startTime),
          };
        }

        return {
          status: 'SUCCESS',
          success: true,
          data: {
            action: 'save_research_summary',
            filePath: input.filePath,
            bytesWritten: content.length,
          },
          stdout: `Saved research summary to ${input.filePath} (${content.length} characters).`,
          message: `Saved research results to ${input.filePath}.`,
          durationMs: Math.round(performance.now() - startTime),
        };
      }

      if (input.action === 'read_file') {
        const res = await filesSkill.execute(
          {
            action: 'get_metadata',
            path: input.filePath,
            overwrite: false,
          },
          {
            isDryRun: !!context.isDryRun,
            killSwitchActive: context.killSwitchActive,
          }
        );

        if (!res.success) {
          return {
            status: 'FAILED',
            success: false,
            error: res.error || `Could not read file at ${input.filePath}`,
            durationMs: Math.round(performance.now() - startTime),
          };
        }

        return {
          status: 'SUCCESS',
          success: true,
          data: {
            action: 'read_file',
            filePath: input.filePath,
            content: res.stdout || JSON.stringify(res.data?.metadata || {}),
          },
          stdout: `Read file metadata: ${input.filePath}`,
          durationMs: Math.round(performance.now() - startTime),
        };
      }

      if (input.action === 'delete_file') {
        // High-Risk safety check
        if (!context.confirmedByUser) {
          return {
            status: 'NEEDS_CONFIRMATION',
            success: false,
            requiresConfirmation: true,
            confirmationPrompt: `Are you sure you want to permanently delete "${input.filePath}"?`,
            message: `Approval required before deleting file: ${input.filePath}.`,
            durationMs: Math.round(performance.now() - startTime),
          };
        }

        const res = await filesSkill.execute(
          {
            action: 'move_to_trash',
            path: input.filePath,
            overwrite: false,
          },
          {
            isDryRun: !!context.isDryRun,
            killSwitchActive: context.killSwitchActive,
          }
        );

        return {
          status: res.success ? 'SUCCESS' : 'FAILED',
          success: res.success,
          data: {
            action: 'delete_file',
            filePath: input.filePath,
            deleted: res.success,
          },
          error: res.error,
          stdout: res.stdout,
          message: res.success ? `Deleted file ${input.filePath}.` : `Failed to delete: ${res.error}`,
          durationMs: Math.round(performance.now() - startTime),
        };
      }

      return {
        status: 'FAILED',
        success: false,
        error: `Unsupported file action: ${input.action}`,
        durationMs: Math.round(performance.now() - startTime),
      };
    } catch (err: any) {
      return {
        status: 'FAILED',
        success: false,
        error: err.message || 'File workflow execution failed',
        durationMs: Math.round(performance.now() - startTime),
      };
    }
  }

  public async verify(
    input: FileWorkflowInput,
    result: ToolExecutionResult<FileWorkflowOutput>
  ): Promise<VerificationResult> {
    if (!result.success && result.status !== 'NEEDS_CONFIRMATION') {
      return { verified: false, actualState: result.status, error: result.error };
    }

    if (input.action === 'save_research_summary') {
      const check = await filesSkill.execute(
        { action: 'get_metadata', path: input.filePath, overwrite: false },
        { isDryRun: false, killSwitchActive: () => false }
      );
      return {
        verified: check.success,
        actualState: check.success ? `File verified on disk: ${input.filePath}` : 'File not found on disk',
      };
    }

    return { verified: true, actualState: `Completed ${input.action}` };
  }
}

export const fileWorkflowTool = new FileWorkflowTool();
